%% Sixty-Source Ensemble Benchmark
% The deterministic ensemble uses 60 source states chosen from accepted
% return-map indices 100:300, with scalar separation
% `abs(X_s-X_t) >= 1.5`.  Each selected source is tested once with the
% Shinbrot bisection method and once with the hybrid method.  The saved
% result is accepted only when its metadata match the current target,
% control settings, method names, source count and table schema.
%
% Regeneration is deliberately controlled by `runExpensiveEnsemble` because
