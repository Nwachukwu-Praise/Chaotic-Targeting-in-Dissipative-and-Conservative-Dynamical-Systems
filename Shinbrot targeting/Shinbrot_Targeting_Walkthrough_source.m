% can target the selected fixed-point neighbourhood from the same source in
% three accepted crossings.  In this example the revised Shinbrot bisection
% method finds the slightly smaller perturbation, while the hybrid method
% finds the smaller final residual.  This single example does not establish
% universal superiority.  The ensemble benchmark is the appropriate place
% to compare distributions of horizons, magnitudes, residuals and costs.
%
% The hybrid method depends on grid resolution and on the rule used to
% refine adjacent brackets.  The bisection method depends on how
% discontinuities in crossing identity are isolated and on the maximum
% isolation depth.  Both methods depend on the Poincare section, target
