%% Shinbrot Targeting Walkthrough
% This Live Script is the principal explanatory walkthrough for the final
% Shinbrot Lorenz targeting implementation in this folder.  It is not a
% replacement for the verified computational functions.  Instead, it calls
% those functions in a documented order and displays the intermediate
% diagnostics, tables and figures inline.
%
% The study has three connected parts:
%
% 1. a deterministic single-source demonstration comparing the verified
%    Shinbrot paper-bisection search with the deterministic
%    grid-first hybrid extension;
% 2. a deterministic 60-source benchmark loaded from verified saved
%    results generated by the current code;
% 3. a fixed-step RK4 Gaussian-noise investigation using the verified
%    paper-bisection method with 40-RK4-step retargeting.
%
% The hybrid method is a deterministic extension for comparison.  It is not
% used in the noise investigation.

%% Reproducible Project Setup
% The script first locates the Shinbrot project folder, moves MATLAB into
% that folder, and adds only that folder to the path.  This avoids hidden
% dependencies on a previous MATLAB session.  The switches below prevent
% expensive studies from being regenerated unless explicitly requested.  In
% normal use the Live Script loads the verified saved ensemble and noise
% results and then plots them inline.

clearvars;
close all;
clc;

projectPath = walkthrough_project_path();
restoredefaultpath;
rehash toolboxcache;
cd(projectPath);
addpath(projectPath);
rng(7, 'twister');

runExpensiveEnsemble = false;
noiseAction = 'validate';

setupTable = table(string(projectPath), runExpensiveEnsemble, ...
    string(noiseAction), ...
    'VariableNames', {'ProjectPath', 'RunExpensiveEnsemble', ...
    'NoiseAction'});
disp(setupTable);

%% Lorenz System
% The controlled Lorenz equations used throughout the implementation are
%
% $$\dot{x} = \sigma(y-x),$$
%
% $$\dot{y} = x(\rho-z)-y+p_{\mathrm{control}},$$
%
% $$\dot{z} = xy-\beta z.$$
%
% The standard Lorenz parameters are
% $\sigma=10$, $\rho=28$ and $\beta=8/3$.  The targeting parameter
% $p_{\mathrm{control}}$ is a bounded additive perturbation in the
% $y$-equation.  It is not a state kick.  During a deterministic targeting
% replay the selected value is held constant from the source Poincare
% crossing until the selected target horizon has been reached.

verifiedBisectionIdentifier = verified_bisection_identifier();

params.sigma = 10;
params.rho = 28;
params.beta = 8/3;
params.zSection = 26.921;
params.xSectionMin = 8.0;
params.crossingDirection = +1;
params.odeOptions = odeset('RelTol', 1e-9, 'AbsTol', 1e-11);
params.eventDisableTime = 1e-6;
params.maxStepOffSection = 1e-5;
params.sectionTolerance = 1e-9;
params.maxTimeToNextValidSection = 100;
params.maxRejectedCrossings = 100;

lorenzParameterTable = table(params.sigma, params.rho, params.beta, ...
    'VariableNames', {'sigma', 'rho', 'beta'});
disp(lorenzParameterTable);

%% Poincare Section
% The implementation converts the continuous Lorenz flow into a scalar
% return-map problem by recording accepted crossings of the half-plane
%
% $$z = 26.921,\qquad x > 8.$$
%
% The event function detects the directed crossing of the plane
% $z=26.921$.  The half-plane condition $x>8$ is then enforced by
% `next_valid_section_crossing`, which rejects plane crossings on the other
% side and continues integration.  The accepted crossing direction is
% positive and the section tolerance is `params.sectionTolerance`.

sectionTable = table(params.zSection, params.xSectionMin, ...
    params.crossingDirection, params.sectionTolerance, ...
    params.eventDisableTime, params.maxStepOffSection, ...
    'VariableNames', {'zSection', 'xSectionMin', ...
    'CrossingDirection', 'SectionTolerance', 'EventDisableTime', ...
    'MaxStepOffSection'});
disp(sectionTable);

%% Target Periodic Orbit
% The target is represented on the accepted Poincare section by the fixed
% scalar coordinate $X_t=13.729$ and the associated three-dimensional
% section state.  Success is not exact equality with the target point;
% instead, a replay is successful when the accepted crossing satisfies
%
% $$|X_n-X_t|\leq 0.008.$$
%
% This neighbourhood definition is necessary because the targeting
% computation is numerical and because the target point is a representative
% fixed point of the return-map dynamics.

target.x = 13.729;
target.state = [13.729; 19.585; params.zSection];
target.tolerance = 0.008;

targetTable = table(target.x, target.state(1), target.state(2), ...
    target.state(3), target.tolerance, ...
    'VariableNames', {'TargetX', 'TargetStateX', 'TargetStateY', ...
    'TargetStateZ', 'TargetTolerance'});
disp(targetTable);

%% Search Settings
% Both deterministic methods use the same dynamical settings, target
% tolerance and parameter bound.  The admissible parameter interval is
% $[-\Delta p,\Delta p]$ with $\Delta p=0.1$.  The deterministic search
% horizon is the number of accepted Poincare crossings after the source
% state.  The hybrid method additionally evaluates the full parameter grid
% before refining verified candidates.

control.deltaP = 0.1;
control.maxSearchCrossings = 12;
control.numParameterSamples = 81;
control.bisectionIterations = 24;
control.maxDiscontinuityIsolationDepth = 24;
control.maxDiscontinuityIntervals = 256;
control.searchMethod = 'hybridGridBisection';

benchmarkSettings.repetitions = 5;

controlTable = table(control.deltaP, control.maxSearchCrossings, ...
    control.numParameterSamples, control.bisectionIterations, ...
    control.maxDiscontinuityIsolationDepth, ...
    control.maxDiscontinuityIntervals, ...
    string(verifiedBisectionIdentifier), ...
    'VariableNames', {'DeltaP', 'MaxSearchCrossings', ...
    'ParameterSamples', 'BisectionIterations', ...
    'MaxDiscontinuityIsolationDepth', 'MaxDiscontinuityIntervals', ...
    'VerifiedBisectionIdentifier'});
disp(controlTable);

%% Source-State Construction
% The nominal return map is generated with `pControl = 0`.  The principal
% source is the full three-dimensional state at the 150th accepted section
% crossing from the initial Lorenz state `[1;1;1]`.  The scalar coordinate
% is used for the return-map search, but the full state is retained for
% every independent replay.

fprintf('Generating the uncontrolled Poincare return map...\n');
X0 = [1; 1; 1];
numMapCrossings = 1200;
sourceIndex = 150;
mapData = generate_return_map(X0, numMapCrossings, params, 0);
if size(mapData.states, 2) < numMapCrossings
    error('Only %d valid section crossings were generated.', ...
        size(mapData.states, 2));
end

sourceState = mapData.states(:, sourceIndex);
if abs(sourceState(1) - target.x) <= target.tolerance
    error('The configured source point lies inside the target interval.');
end
sourceX = sourceState(1);

sourceSummary = table(sourceIndex, sourceX, target.x, ...
    abs(sourceX - target.x), numMapCrossings, ...
    'VariableNames', {'SourceIndex', 'SourceX', 'TargetX', ...
    'InitialScalarSeparation', 'GeneratedMapCrossings'});
disp(sourceSummary);

%% Lorenz Attractor, Section and Accepted Crossings
% The following figure shows the nominal trajectory used to build the
% return map, the accepted half-plane, the target point and the selected
% source point.  The accepted section states are overlaid so the scalar
% sequence can be seen as samples of the continuous flow.

walkthrough_plot_lorenz_section(mapData, sourceState, target, params);

%% Scalar Return Map
% Consecutive accepted crossings define a one-dimensional return-map view:
% $X_{n+1}=F(X_n)$.  The target fixed point is shown against the identity
% line.  This plot is only a scalar projection of the full section state;
% all replay verification still reintegrates the full Lorenz equations.

walkthrough_plot_return_map(mapData, sourceState, target);

%% Uncontrolled Baseline
% The uncontrolled baseline starts from the same source state and sets
% `pControl = 0`.  It counts accepted section crossings until the target
% neighbourhood is reached or until the configured maximum number of
% crossings is exhausted.  This is the natural-recurrence reference against
% which the controlled searches are compared.

fprintf('Running the uncontrolled recurrence baseline...\n');
uncontrolled = uncontrolled_hitting_time_1d( ...
    sourceState, target, params, 2000);

uncontrolledTable = table(uncontrolled.hit, uncontrolled.numCrossings, ...
    uncontrolled.physicalTime, numel(uncontrolled.xSequence), ...
    'VariableNames', {'Hit', 'AcceptedCrossingsToHit', ...
    'PhysicalTimeToHit', 'StoredScalarSequenceLength'});
disp(uncontrolledTable);

%% Shinbrot Discontinuity-Aware Bisection
% The verified Shinbrot search calls `search_parameter_to_target` with the
% dispatcher identifier `shinbrotDiscontinuityAwareBisection`.  Internally,
% `run_shinbrot_discontinuity_aware_bisection` subdivides the full bounded
% interval, compares ordered left/right crossing signatures, isolates
% continuous target brackets, and then refines only brackets whose endpoint
% images remain on the same branch and contain the target.
%
% This section does not reproduce a second bisection algorithm.  It calls
% the verified `.m` implementation and then displays the search metadata:
% discontinuity counts, crossing-signature evaluations, bracket bounds,
% selected horizon, selected parameter and target error.

fprintf('Running the verified Shinbrot bisection search...\n');
bisectionControl = control;
bisectionControl.searchMethod = verifiedBisectionIdentifier;
bisectionSearch = search_parameter_to_target( ...
    sourceState, target, params, bisectionControl, ...
    verifiedBisectionIdentifier);
assert_verified_bisection_search( ...
    bisectionSearch, verifiedBisectionIdentifier, ...
    'principal deterministic bisection');

bisectionReplayTimer = tic;
bisectionReplay = walkthrough_replay_parameter( ...
    sourceState, target, params, bisectionSearch);
bisectionReplay.replayTime = toc(bisectionReplayTimer);

bisectionSearchTable = walkthrough_bisection_diagnostics( ...
    bisectionSearch, bisectionReplay);
disp(bisectionSearchTable);

%% Hybrid Grid-First/Bisection Method
% The hybrid method is an addition to the original Shinbrot procedure.  At
% each horizon it evaluates the complete parameter grid, records all direct
% grid hits and all adjacent sign-change brackets, then bisects each
% verified adjacent bracket.  Candidate selection is lexicographic:
%
% 1. smallest targeting horizon;
% 2. smallest `abs(pControl)`;
% 3. smallest final target residual.
%
% The search is still verified by direct integration from the original
% source state.  A sign change alone is not treated as a hit.

fprintf('Running the deterministic grid-first hybrid search...\n');
hybridControl = control;
hybridControl.searchMethod = 'hybridGridBisection';
hybridSearch = search_parameter_to_target( ...
    sourceState, target, params, hybridControl, 'hybridGridBisection');

hybridReplayTimer = tic;
hybridReplay = walkthrough_replay_parameter( ...
    sourceState, target, params, hybridSearch);
hybridReplay.replayTime = toc(hybridReplayTimer);

hybridSearchTable = walkthrough_hybrid_diagnostics(hybridSearch, hybridReplay);
disp(hybridSearchTable);

hybridFeatureTable = walkthrough_hybrid_feature_table( ...
    hybridSearch, target);
disp(hybridFeatureTable);

%% Principal Deterministic Comparison
% Both procedures are now compared from the same source.  The reference
% values below are verification references from the current implementation,
% not values used to select the controls.  The table is generated from the
% executed searches and independent replays.

principalComparison = walkthrough_principal_comparison_table( ...
    bisectionSearch, bisectionReplay, hybridSearch, hybridReplay);
disp(principalComparison);

% The checks below assert the properties a valid result must have, not the
% particular numbers a given implementation happens to return.  Pinning
% literal values here made the walkthrough a record of one implementation
% rather than a verification of the method, and it is what allowed this file
% and Table 2 of the report to drift apart.  The returned values are
% displayed in principalComparison above rather than asserted.

walkthrough_assert_valid_result(bisectionSearch, bisectionReplay, ...
    target, control, 'Shinbrot bisection');
walkthrough_assert_valid_result(hybridSearch, hybridReplay, ...
    target, control, 'Grid-first hybrid');

% The two methods are only comparable when they report the same horizon.
% They are not required to agree, and a disagreement is a result rather than
% a failure, so it is reported and not asserted.
if bisectionSearch.horizon ~= hybridSearch.horizon
    fprintf(['Note: the methods selected different horizons (%d and %d). ', ...
        'Perturbation magnitudes are not directly comparable at ', ...
        'different horizons.\n'], bisectionSearch.horizon, hybridSearch.horizon);
end

%% Controlled Replay and Verification
% The selected controls are replayed independently of the search
% calculations.  A method is reported as successful here only if the
% reintegrated controlled trajectory enters the target neighbourhood at the
% selected accepted crossing.

replayVerification = table( ...
    ["Shinbrot bisection"; "Grid-first hybrid"], ...
    [bisectionReplay.hit; hybridReplay.hit], ...
    [bisectionReplay.numCrossings; hybridReplay.numCrossings], ...
