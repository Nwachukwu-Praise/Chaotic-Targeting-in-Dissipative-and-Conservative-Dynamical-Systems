%% Noise-Robustness Investigation
% The final investigation uses fixed-step RK4 because adaptive internal
% steps would make per-step coordinate noise ambiguous.  In
% `next_valid_section_crossing_noisy_rk4`, independent Gaussian noise is
% applied before the corresponding integration step:
%
% $$X \leftarrow X+\sigma_{\mathrm{noise}}\eta,\qquad
% \eta\sim N(0,I_3).$$
%
% Section crossings are detected manually by linear interpolation across
% the integrated RK4 segment.  Crossings caused solely by the instantaneous
% noise jump are deliberately excluded.  The final noise study uses the
% verified paper-bisection method only.  The paper-mode reconstruction uses
% `paper40StepRetargetMode`: after every 40 completed RK4 steps, the
% verified paper-bisection search is rerun from the current full state, even
% when that state is off the Poincare section.  The section-retarget mode is
% retained only as a separately labelled project extension.

